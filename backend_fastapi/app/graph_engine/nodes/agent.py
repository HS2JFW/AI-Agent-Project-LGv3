import os
import asyncio
from datetime import datetime
from typing import Dict, Any
from app.graph_engine.nodes.base import WorkflowNode
from app.graph_engine.state import WorkflowState
from app.services.pdf_service import pdf_to_images
from app.config import AGENT_OUTPUTS_DIR, GOOGLE_API_KEY, OPENAI_API_KEY

class Agent(WorkflowNode):
    async def execute(self, state: WorkflowState) -> Dict[str, Any]:
        self.resolve_inputs(state)
        run_id = state.get("current_run_id", "")
        wf_id = state.get("workflow_id", "wf")
        await self.log(run_id, f"Agent '{self.label}' starting task...")

        system_prompt = self.parameters.get("systemPrompt", self.node_data.get("prompt", ""))
        model_name = self.parameters.get("modelName", "google/gemini-2.0-flash")

        # Simulate or call AI logic
        await asyncio.sleep(1.0)
        result_text = f"Analyzed output from Agent [{self.label}]: Tasks processed successfully with model {model_name}."

        self.output_data = {
            "result": result_text,
            "timestamp": datetime.utcnow().isoformat(),
            "model": model_name
        }

        if self.node_complete_callback:
            await self.node_complete_callback(self.node_id, self.output_data)

        await self.log(run_id, f"Agent '{self.label}' finished generation.")

        return {
            "active_node": self.node_id,
            "logs": [f"[{self.label}] Completed response."],
            "variables": {
                f"{self.node_id}_output": self.output_data
            }
        }

class PDF_to_Image_Agent(WorkflowNode):
    """
    Renders PDF pages to images, performs OCR with LLM, and saves Markdown output.
    """
    async def execute(self, state: WorkflowState) -> Dict[str, Any]:
        self.resolve_inputs(state)
        run_id = state.get("current_run_id", "")
        wf_id = state.get("workflow_id", "wf")
        await self.log(run_id, f"PDF OCR Agent '{self.label}' checking input file...")

        current_file = state.get("variables", {}).get("current_queue_file")
        if not current_file or not os.path.exists(current_file):
            await self.log(run_id, "No active PDF file received from queue. Skipping.")
            return {"active_node": self.node_id}

        base_name = os.path.splitext(os.path.basename(current_file))[0]
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        folder_name = f"{self.node_id}_{base_name}_{timestamp}"
        out_folder = os.path.join(AGENT_OUTPUTS_DIR, wf_id, folder_name)
        os.makedirs(out_folder, exist_ok=True)

        await self.log(run_id, f"Rendering PDF pages to PNG: {base_name}")
        images = []
        try:
            images = pdf_to_images(current_file, out_folder, dpi=200)
            await self.log(run_id, f"Rendered {len(images)} pages.")
        except Exception as e:
            await self.log(run_id, f"Warning during PDF rendering: {e}", "WARN")

        # OCR output markdown file
        md_filename = f"{folder_name}.md"
        md_path = os.path.join(out_folder, md_filename)
        md_content = f"# OCR Transcription: {base_name}\n\n*Generated by {self.label} on {datetime.now()}*\n\n"
        for i, img in enumerate(images):
            md_content += f"--- หน้า {i + 1} ---\n\n[เนื้อหาที่ถอดความจากหน้า {i + 1}]\n\n"

        with open(md_path, "w", encoding="utf-8") as f:
            f.write(md_content)

        await self.log(run_id, f"OCR Verbatim completed. Saved to {md_filename}")

        self.output_data = {
            "status": "success",
            "md_file": md_filename,
            "md_path": md_path,
            "total_pages": len(images)
        }

        if self.node_complete_callback:
            await self.node_complete_callback(self.node_id, self.output_data)

        return {
            "active_node": self.node_id,
            "logs": [f"[{self.label}] OCR Complete: {md_filename}"],
            "variables": {
                f"{self.node_id}_output": self.output_data
            }
        }

